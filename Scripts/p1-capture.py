#!/usr/bin/env python3 -I
# P1 validation (DATABASE-CAPACITY-PLAN.md §9): what the radio readers say
# about "played on a show" for a fixed sample of artists and shows, read-only,
# so the output before and after a change can be compared. The B1 method
# (Scripts/b1-capture.py), extended to the show's end of the edge.
#
#   Scripts/p1-capture.py sql <sample.json> <pilot_demand.json> [prefix] > capture.sql
#   supabase db query --linked -f capture.sql > capture.json
#   Scripts/p1-capture.py compare <before.json> <after.json>
#
# `prefix` names the functions read: `public.` (default) for what is live, or
# `pg_temp.p87_` for the proposed bodies loaded as session-local functions in
# the same call (nothing shared is written).
import json, sys

def load(path):
    text = open(path).read()
    return json.loads(text[text.find("{"):text.rfind("}") + 1])["rows"][-1]["c"]

if sys.argv[1] == "sql":
    sample = json.load(open(sys.argv[2]))
    demand = json.load(open(sys.argv[3]))
    fn = sys.argv[4] if len(sys.argv) > 4 else "public."
    artists = [s for s in sample if s["kind"] == "artist"]
    shows = [s for s in sample if s["kind"] == "show"]
    ids = ",".join(f"'{a['id']}'::uuid" for a in artists)
    nodes = [{"id": f"artist:{a['key']}", "kind": "artist", "key": a["key"], "provider": "", "handle": ""} for a in artists]
    for s in shows:
        provider, handle = s["key"].split("|", 1)
        provider = "lot" if provider == "lotradio" else provider
        nodes.append({"id": f"broadcast:{s['key']}", "kind": "broadcast", "key": s["key"], "provider": provider, "handle": handle})
    nodes += [{k: v for k, v in n.items() if k != "why"} for n in demand["nodes"]]
    batches = [nodes[i:i + 6] for i in range(0, len(nodes), 6)]
    q = lambda s: "$q$" + s + "$q$"
    arr = lambda xs: "array[" + ",".join(q(json.dumps(b)) for b in xs) + "]"
    print(f"""-- Generated by Scripts/p1-capture.py: read-only.
with ids(id) as (select unnest(array[{ids}])),
relations as (
  select i.id, json_agg(json_build_object('t', r.relationship_type, 'other', r.entity_id, 'n', r.evidence_count,
         'c', round(r.confidence::numeric, 6), 'm', r.metadata) order by r.relationship_type, r.entity_id) as rows
  from ids i cross join lateral {fn}artist_radio_relations(i.id, 200) r group by i.id),
explore as (select b, {fn}explore_knowledge(b::jsonb, '{{}}') as a from unnest({arr(batches)}) b),
answers as (select b, {fn}knowledge_answers(b::jsonb, '{{}}') as a from unnest({arr(batches)}) b)
select json_build_object(
  'relations', (select json_object_agg(id, rows) from relations),
  'explore', (select json_object_agg(n.key, n.value->'edges') from explore x, jsonb_each(x.a->'nodes') n),
  'answers', (select json_object_agg(n.key, n.value->'edges') from answers x, jsonb_each(x.a->'nodes') n)
) as c;""")
    sys.exit()

before, after = load(sys.argv[2]), load(sys.argv[3])

def norm(rows, reader, kind):
    out = []
    for r in rows or []:
        if reader == "relations":
            if (r["t"] == "played_by") == (kind == "show"):
                out.append(json.dumps(r, sort_keys=True))
        else:
            if (r["kind"] == "playedInShow") == (kind == "show"):
                out.append(json.dumps(r, sort_keys=True))
    return sorted(out)

report = {}
for reader in ("relations", "explore", "answers"):
    for kind in ("show", "other"):
        b, a = before.get(reader) or {}, after.get(reader) or {}
        same = changed = gone = new = 0
        examples = []
        for key in sorted(set(b) | set(a)):
            x, y = norm(b.get(key), reader, kind), norm(a.get(key), reader, kind)
            if x == y:
                same += 1
                continue
            changed += 1
            only_x = [e for e in x if e not in y] if len(x) < 5000 else sorted(set(x) - set(y))
            only_y = [e for e in y if e not in x] if len(y) < 5000 else sorted(set(y) - set(x))
            gone += len(only_x); new += len(only_y)
            if len(examples) < 6:
                examples.append({"key": key, "rows_before": len(x), "rows_after": len(y),
                                 "only_before": only_x[:3], "only_after": only_y[:3]})
        report[f"{reader}/{'playedInShow' if kind == 'show' else 'everything else'}"] = {
            "same": same, "changed": changed, "rows_only_before": gone, "rows_only_after": new, "examples": examples}
print(json.dumps(report, indent=1))
