#!/usr/bin/env python3 -I
# B1 validation (DATABASE-CAPACITY-PLAN.md): what the four radio readers say
# about "played next to each other" for a fixed sample of artists, read-only,
# so the output before and after a change can be compared.
#
#   Scripts/b1-capture.py sql <sample-list.json> <pilot_demand.json> > capture.sql
#   supabase db query --linked -f capture.sql > capture.json
#   Scripts/b1-capture.py compare <before.json> <after.json>
import json, sys

def load(path):
    text = open(path).read()
    return json.loads(text[text.find("{"):text.rfind("}") + 1])["rows"][0]["c"]

if sys.argv[1] == "sql":
    sample = json.load(open(sys.argv[2]))
    demand = json.load(open(sys.argv[3]))
    ids = ",".join(f"'{a['id']}'::uuid" for a in sample)
    keys = [a["key"] for a in sample]
    nodes = [{"id": f"artist:{k}", "kind": "artist", "key": k, "provider": "", "handle": ""} for k in keys]
    nodes += [{k: v for k, v in n.items() if k != "why"} for n in demand["nodes"] if n["kind"] == "artist"]
    batches = [nodes[i:i + 6] for i in range(0, len(nodes), 6)]
    q = lambda s: "$q$" + s + "$q$"
    print(f"""-- Generated by Scripts/b1-capture.py: read-only.
with ids(id) as (select unnest(array[{ids}])),
relations as (
  select i.id, json_agg(json_build_object('t', r.relationship_type, 'other', r.entity_id, 'n', r.evidence_count,
         'c', round(r.confidence::numeric, 6), 'm', r.metadata) order by r.relationship_type, r.entity_id) as rows
  from ids i cross join lateral public.artist_radio_relations(i.id, 200) r group by i.id),
alongside as (
  select k, public.dig_radio_for_artists(array[k], 50)->'alongside' as rows
  from unnest(array[{",".join(q(k) for k in keys)}]) k),
explore as (
  select b, public.explore_knowledge(b::jsonb, '{{}}') as a
  from unnest(array[{",".join(q(json.dumps(b)) for b in batches)}]) b),
answers as (
  select b, public.knowledge_answers(b::jsonb, '{{}}') as a
  from unnest(array[{",".join(q(json.dumps(b)) for b in batches)}]) b)
select json_build_object(
  'relations', (select json_object_agg(id, rows) from relations),
  'alongside', (select json_object_agg(k, rows) from alongside),
  'explore', (select json_object_agg(n.key, (select json_agg(e order by e::text) from jsonb_array_elements(n.value->'edges') e
                                             where e->>'kind' = 'frequentlyPlayedNearby'))
              from explore x, jsonb_each(x.a->'nodes') n),
  'answers', (select json_object_agg(n.key, (select json_agg(e order by e::text) from jsonb_array_elements(n.value->'edges') e
                                             where e->>'kind' = 'frequentlyPlayedNearby'))
              from answers x, jsonb_each(x.a->'nodes') n)
) as c;""")
    sys.exit()

before, after = load(sys.argv[2]), load(sys.argv[3])
def norm(rows, reader):
    out = set()
    for r in rows or []:
        if reader == "relations":
            if r["t"] != "radio_neighbor":
                out.add(("show", r["other"], r["n"]))
            else:
                out.add(("near", r["other"], r["n"], str(r["c"]), json.dumps(r["m"], sort_keys=True)))
        elif reader == "alongside":
            out.add((r["artist_id"], r["evidence_count"], r["via"]))
        else:
            out.add((r["to"]["name"], r["occurrences"], round(float(r["confidence"]), 6), r["reason"]))
    return out

report = {}
for reader in ("relations", "alongside", "explore", "answers"):
    b, a = before.get(reader) or {}, after.get(reader) or {}
    same = changed = 0
    gone, new = 0, 0
    examples = []
    for key in sorted(set(b) | set(a)):
        x, y = norm(b.get(key), reader), norm(a.get(key), reader)
        if x == y:
            same += 1
        else:
            changed += 1
            gone += len(x - y); new += len(y - x)
            if len(examples) < 6:
                examples.append({"key": key, "only_before": sorted(map(str, x - y))[:3], "only_after": sorted(map(str, y - x))[:3]})
    report[reader] = {"identical": same, "different": changed, "rows_only_before": gone, "rows_only_after": new, "examples": examples}
print(json.dumps(report, indent=1, ensure_ascii=False))
